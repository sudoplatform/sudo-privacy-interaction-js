import { Pagination } from './common'

/**
 * Properties required to connect a virtual presence with a refresh token.
 *
 * @interface ConnectVirtualPresenceWithRefreshTokenInput
 * @property {string} refreshToken The refresh token value.
 * @property {string} providerIdentity The identity associated with the provider.
 * @property {string[]} scopes Optional OAuth scopes associated with the token.
 * @property {number} expiresInEpochMs Optional expiration time in milliseconds since epoch.
 */
export interface ConnectVirtualPresenceWithRefreshTokenInput {
  refreshToken: string
  providerIdentity: string
  scopes?: string[]
  expiresInEpochMs?: number
}

/**
 * Properties required to list virtual presences for this client.
 *
 * @interface ListVirtualPresencesInput
 * @property {number} limit Number of items to return.
 * @property {string} nextToken A token generated by a previous call.
 */
// eslint-disable-next-line @typescript-eslint/no-empty-object-type
export interface ListVirtualPresencesInput extends Pagination {}

/**
 * Properties required to rescan a virtual presence.
 *
 * @interface RescanVirtualPresenceInput
 * @property {string} id The unique identifier of the virtual presence to rescan.
 * @property {ScanOptions} options Optional scan options to control the rescan behavior.
 */
export interface RescanVirtualPresenceInput {
  id: string
  options?: ScanOptions
}

/**
 * Options to control a rescan operation.
 *
 * @interface ScanOptions
 * @property {number} maximumItemsProcessed Maximum number of items to process during the scan.
 * @property {string} earliestScanDate Earliest date boundary for the scan (ISO 8601 string).
 * @property {string} latestScanDate Latest date boundary for the scan (ISO 8601 string).
 * @property {string[]} excludeDomains Domains to exclude from the scan.
 * @property {string[]} excludeCategories Categories to exclude from the scan.
 */
export interface ScanOptions {
  maximumItemsProcessed?: number
  earliestScanDate?: string
  latestScanDate?: string
  excludeDomains?: string[]
  excludeCategories?: string[]
}
